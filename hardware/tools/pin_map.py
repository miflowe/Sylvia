"""Generate docs/pin-map.md from kicad/sylvia-node.net (so the map can't drift from the schematic),
and check it against firmware/components/board/include/board.h.

    python -I hardware/tools/pin_map.py
"""
import pathlib
import re
import sys

HW = pathlib.Path(__file__).resolve().parents[1]
NET = HW / "kicad" / "sylvia-node.net"
OUT = HW / "docs" / "pin-map.md"
BOARD_H = HW / "firmware" / "components" / "board" / "include" / "board.h"

# Notes per ESP32 GPIO: function, direction, RTC-capable (deep-sleep wake/hold), caveats.
NOTES = {
    "IO0": "BOOT button (strapping: low at reset = download mode)",
    "IO1": "ADC1_CH0: CO_VOUT backup reading", "IO2": "ADC1_CH1: ZE07-CO DAC (alt, 0 Ω DNP)",
    "IO3": "strapping (JTAG source): not used", "IO4": "I2C0 SDA, 100 kHz (LMP91000 max)",
    "IO5": "I2C0 SCL", "IO6": "I2C1 SDA (SEN66 cable), 100 kHz", "IO7": "I2C1 SCL",
    "IO8": "LS1 ON: SEN66 rail (hold during deep sleep)", "IO9": "LS2 ON: alternates rail",
    "IO10": "charge inhibit (high = BQ24650 off)", "IO11": "MAX17048 ALRT (open-drain): ext1 wake",
    "IO12": "BQ24650 STAT1 (low = charging)", "IO13": "BQ24650 STAT2 (low = done)",
    "IO14": "status LED", "IO15": "buzzer PWM 2.7 kHz (DNP)", "IO16": "RAK3172 NRST (open-drain)",
    "IO17": "UART1 TX → RAK3172 UART2 RX (AT, 115200)", "IO18": "UART1 RX ← RAK3172 UART2 TX",
    "USB_D-": "native USB (flash, console)", "USB_D+": "native USB",
    "IO21": "tamper pads (100k pull-up, closed = low): ext1 wake",
    "IO38": "VBUS detect (divider, 2.5 V)", "IO39": "RAK3172 BOOT0 (high = bootloader)",
    "IO40": "PMSA003I SET (alt)", "IO41": "UART2 RX ← ZE07-CO TXD (alt)", "IO42": "UART2 TX → ZE07-CO RXD (alt)",
    "TXD0": "UART0 TX → J6 debug header", "RXD0": "UART0 RX ← J6",
    "IO45": "strapping (VDD_SPI voltage): must stay low/floating", "IO46": "strapping: not used",
    "IO47": "ADS1115 ALERT/RDY", "IO48": "spare → test point",
    "IO35": "octal PSRAM: NEVER use", "IO36": "octal PSRAM: NEVER use", "IO37": "octal PSRAM: NEVER use",
    "EN": "reset: 10k + 1 µF + RESET button",
}
RTC = {f"IO{i}" for i in range(0, 22)}


def parse():
    text = NET.read_text(encoding="utf-8")
    pins = {}
    for m in re.finditer(r'\(net\s*\(code "?\d+"?\)\s*\(name "([^"]*)"\)', text):
        end = text.find("(net", m.end())
        blk = text[m.end(): end if end > 0 else len(text)]
        for ref, pin, fn in re.findall(r'\(ref "([^"]+)"\)\s*\(pin "([^"]+)"\)(?:\s*\(pinfunction "([^"]*)"\))?', blk):
            pins.setdefault(ref, {})[pin] = (m.group(1), fn)
    return pins


def symbol_pins(name):
    lib = (HW / "kicad" / "lib" / "sylvia.kicad_sym").read_text(encoding="utf-8")
    start = lib.index(f'\n\t(symbol "{name}"')
    end = lib.find('\n\t(symbol "', start + 5)
    blk = lib[start:end]
    ext = re.search(r'\(extends "([^"]+)"', blk)
    if ext:
        return symbol_pins(ext.group(1))
    return {n: nm for nm, n in re.findall(r'\(name "([^"]*)".*?\(number "([^"]*)"', blk, re.S)}


def main():
    pins = parse()
    names = symbol_pins("ESP32-S3-WROOM-1")
    u1 = {num: (pins["U1"].get(num, ("NC", ""))[0], nm) for num, nm in names.items()}
    rak_names = symbol_pins("RAK3172-xx-8-SM-xI")
    pins["U2"] = {n: (net, rak_names.get(n, "")) for n, (net, _) in pins["U2"].items()}
    rows = []
    for num in sorted(u1, key=int):
        net, fn = u1[num]
        net = "NC" if net.startswith("__NOCONNECT") or net == "" else net
        rows.append(f"| {num} | {fn} | {'✓' if fn in RTC else ''} | `{net}` | {NOTES.get(fn, '')} |")
    u2 = pins["U2"]
    rak = [f"| {n} | {u2[n][1]} | `{u2[n][0]}` |" for n in sorted(u2, key=int)
           if not u2[n][0].startswith("__NOCONNECT")]
    OUT.write_text(
        "# Pin map (generated by `tools/pin_map.py` from `kicad/sylvia-node.net`)\n\n"
        "Firmware constants live in `firmware/components/board/include/board.h`; this script fails if they disagree.\n\n"
        "## ESP32-S3-WROOM-1-N8R8 (U1)\nRTC = usable as a deep-sleep wake source / held level.\n\n"
        "| Pad | Pin | RTC | Net | Use |\n|---|---|---|---|---|\n" + "\n".join(rows) +
        "\n\n## RAK3172 (U2): connected pads\n| Pad | Pin | Net |\n|---|---|---|\n" + "\n".join(rak) + "\n",
        encoding="utf-8")
    print(f"pin map: {len(rows)} ESP32 pads, {len(rak)} RAK3172 pads")
    if BOARD_H.exists():
        bad = 0
        h = BOARD_H.read_text(encoding="utf-8")
        by_net = {net: fn for net, fn in u1.values()}
        for name, gpio in re.findall(r"#define PIN_(\w+)\s+GPIO_NUM_(\d+)", h):
            fn = f"IO{gpio}"
            nets = [n for n, f in u1.values() if f == fn]
            if not nets or nets[0] != name:
                print(f"board.h PIN_{name} = GPIO{gpio}, but the netlist has {fn} on {nets[0] if nets else '?'}")
                bad += 1
        print("board.h matches the netlist" if not bad else f"{bad} board.h mismatches")
        del by_net
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
