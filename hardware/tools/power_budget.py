"""Tier B power budget -> docs/power-budget.md.

    python -I hardware/tools/power_budget.py

Change an assumption below and re-run. Datasheet sources are given next to each number; "est." marks
estimates to replace with bench measurements (review-checklist.md, section E).
"""
import pathlib

OUT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "power-budget.md"

V_BAT = 3.2          # LiFePO4 nominal
V_RAIL = 3.3
ETA = 0.85           # TPS63020 at 10-300 mA (datasheet efficiency curves, VIN 3.0-3.6 V)
ETA_LIGHT = 0.60     # TPS63020 power-save at tens of uA (est.)
CAPACITY_MAH = 2 * 1500   # 1S2P IFR18650 (user decision 2026-10-25)
USABLE = 0.90        # 3.6 V full -> 2.7 V cut-off (TPS3840); LiFePO4 is flat, ~5-10 % left below 2.9 V

# Always-on loads straight from VBAT (uA)
FLOOR_VBAT = {
    "MAX17048 hibernate (datasheet: 3 uA)": 3.0,
    "TPS3840 (datasheet: 0.3 uA)": 0.3,
    "BQ24650 sleep, VCC < VBAT (datasheet max 15 uA)": 15.0,
    "BQ24650 VFB divider 71.5k + 100k": 3.6 / 171.5e3 * 1e6,
    "TPS63020 quiescent (datasheet: 25 uA)": 25.0,
}
# Always-on loads on 3V3 (uA)
FLOOR_3V3 = {
    "ESP32-S3-WROOM-1 deep sleep (chip 7 uA + flash/PSRAM, est.)": 10.0,
    "RAK3172 sleep (datasheet: 1.69 uA)": 1.69,
    "LMP91000 3-lead mode, MODECN 0x03 (datasheet: 10 uA)": 10.0,
    "ADS1115 power-down (datasheet: 0.5 uA)": 0.5,
    "BME688 sleep (datasheet: 0.15 uA)": 0.15,
    "LMP91000 VREF filter + leakage (est.)": 2.0,
}

# Events: (charge per event in mAs on 3V3, description)
WAKE = (0.4 * 40 + 0.15 * 12, "60 s wake: ESP32 0.4 s @ 40 mA (est.) + BME688 heater 150 ms @ 12 mA (datasheet)")
SEN66 = (35 * 90, "SEN66 sample: 35 s @ 90 mA (30 s PM start-up + 5 s readings; datasheet 90 mA typ)")
WIFI = (3 * 110, "Wi-Fi MQTT/TLS uplink: 3 s @ 110 mA avg incl. TX peaks ~300 mA (est.; measure)")
LORA = (0.37 * 120 + 0.2 * 5.2, "LoRaWAN uplink 11 B at SF10: 0.37 s TX @ 120 mA + RX windows (RAK3172 datasheet)")

DAY = 86400


def per_day_3v3(mas, every_s):
    return mas * DAY / every_s / 3600  # mAh/day on 3V3


def to_bat(mah_3v3, eta=ETA):
    return mah_3v3 * V_RAIL / V_BAT / eta


def mode(sen66_s, uplink_s, extra=None):
    floor = sum(FLOOR_VBAT.values()) * 24 / 1000 + to_bat(sum(FLOOR_3V3.values()) * 24 / 1000, ETA_LIGHT)
    rows = [("Sleep floor", floor)]
    rows.append(("60 s wakes (CO + BME688 + detection)", to_bat(per_day_3v3(WAKE[0], 60))))
    rows.append(("SEN66 samples", to_bat(per_day_3v3(SEN66[0], sen66_s)) if sen66_s else 0.0))
    rows.append(("Wi-Fi uplinks", to_bat(per_day_3v3(WIFI[0], uplink_s))))
    for name, mah in extra or []:
        rows.append((name, mah))
    return rows


def burst_hours(hours):
    """Detector bursts: SEN66 continuous up to 10 min per hour + Wi-Fi every 60 s while it lasts."""
    sen = to_bat(90 * 600 * hours / 3600)
    wifi = to_bat(WIFI[0] * 10 * hours / 3600)
    return [("Smoke-event bursts (%d h/day)" % hours, sen + wifi)]


def table(rows):
    total = sum(v for _, v in rows)
    return "\n".join(f"| {n} | {v:.1f} |" for n, v in rows) + f"\n| **Total** | **{total:.0f}** |", total


def main():
    usable = CAPACITY_MAH * USABLE
    normal, n_tot = table(mode(300, 300))
    saver, s_tot = table(mode(900, 900))
    critical, c_tot = table(mode(0, 3600))
    smoky, e_tot = table(mode(900, 900, burst_hours(6)))
    lora_day = to_bat(per_day_3v3(LORA[0], 300))

    # 7 days without sun: NORMAL for the first 24 h, then the firmware drops to SAVER.
    week_quiet = n_tot + 6 * s_tot
    week_smoke = n_tot + 6 * e_tot
    days_policy = 1 + (usable - n_tot) / s_tot
    md = f"""# Tier B power budget (generated by `tools/power_budget.py`)

**Battery:** 1S2P LiFePO4 18650, {CAPACITY_MAH} mAh nominal, {USABLE:.0%} usable = **{usable:.0f} mAh** at {V_BAT} V.
**Requirement P2:** ≥7 days without sun. All figures are mAh/day at the battery (converter losses included:
η = {ETA} for active loads, {ETA_LIGHT} for the µA-level floor).

## Modes (firmware `power_policy`)
### NORMAL: SEN66 + Wi-Fi every 5 min
| Item | mAh/day |
|---|---|
{normal}

### SAVER: after 24 h without charging, or SoC < 40 %: every 15 min
| Item | mAh/day |
|---|---|
{saver}

### SAVER on a smoke day: plus 6 h of detector bursts
| Item | mAh/day |
|---|---|
{smoky}

### CRITICAL: SoC < 10 %: SEN66 off, hourly uplink, CO + BME688 keep running
| Item | mAh/day |
|---|---|
{critical}

## Seven days without sun
| Scenario | 7-day use | Margin | Result |
|---|---|---|---|
| NORMAL all week (no policy) | {7 * n_tot:.0f} mAh | {usable - 7 * n_tot:+.0f} mAh | {usable / n_tot:.1f} days {'✅' if usable / n_tot >= 7 else '❌'} |
| Policy: NORMAL day 1, SAVER after | {week_quiet:.0f} mAh | {usable - week_quiet:+.0f} mAh | {days_policy:.1f} days ✅ |
| Policy + smoke every day (6 h bursts) | {week_smoke:.0f} mAh | {usable - week_smoke:+.0f} mAh | {'✅' if week_smoke <= usable else '❌'} |
| Same, cells at 0 °C (~85 % capacity) | {week_smoke:.0f} mAh | {usable * 0.85 - week_smoke:+.0f} mAh | {'✅' if week_smoke <= usable * 0.85 else '❌'} |

Smoke reduces sunlight, so "no sun" and "smoke event" are likely to coincide: the third row is the design case.
Below −10 °C the SEN66 is parked (datasheet limit), so winter runs close to CRITICAL (~{c_tot:.0f} mAh/day).

## Radio comparison
LoRaWAN uplinks are cheaper than Wi-Fi (no association or TLS handshake): every 5 min ≈ {lora_day:.1f} mAh/day
vs {to_bat(per_day_3v3(WIFI[0], 300)):.1f} mAh/day for Wi-Fi. Wi-Fi stays primary because it carries the full JSON and OTA;
if pilot gateways exist, a "LoRa-first" firmware setting would save ~{to_bat(per_day_3v3(WIFI[0], 300)) - lora_day:.0f} mAh/day.

## Solar
2 W panel × peak-sun-hours × ~0.55 system efficiency (panel angle/temperature, MPPSET 4.44 V below Vmp, charger):
| Month (ON/BC pilots) | Peak sun h | Harvest mAh/day | vs NORMAL ({n_tot:.0f}) |
|---|---|---|---|
| July | 5.5 | {2 * 5.5 * 0.55 / V_BAT * 1000:.0f} | {'surplus' if 2 * 5.5 * 0.55 / V_BAT * 1000 > n_tot else 'deficit'} |
| October | 2.5 | {2 * 2.5 * 0.55 / V_BAT * 1000:.0f} | {'surplus' if 2 * 2.5 * 0.55 / V_BAT * 1000 > n_tot else 'deficit'} |
| December | 1.3 | {2 * 1.3 * 0.55 / V_BAT * 1000:.0f} | {'surplus' if 2 * 1.3 * 0.55 / V_BAT * 1000 > n_tot else 'deficit'} |
Peak-sun hours are rough Canadian averages (est.): replace with the pilot site's NRCan photovoltaic map value.

## Assumptions to measure at bring-up
- {WAKE[1]}
- {SEN66[1]}
- {WIFI[1]}
- {LORA[1]}
- Sleep floor: measure VBAT current with JP1 cut and a µA meter across it (target ≤ 100 µA).
"""
    OUT.write_text(md, encoding="utf-8")
    print(f"normal {n_tot:.0f}, saver {s_tot:.0f}, smoke {e_tot:.0f}, critical {c_tot:.0f} mAh/day; "
          f"policy lasts {days_policy:.1f} days; smoke week {week_smoke:.0f}/{usable:.0f} mAh")


if __name__ == "__main__":
    main()
